  // Pre-render glyph masks into small canvases per color on demand (cached).
  const cache = {};
  function glyphCanvas(ch, color) {
    const key = ch + '|' + color;
    if (cache[key]) return cache[key];
    const rows = F[ch] || F['?'];
    const c = document.createElement('canvas'); c.width = 5; c.height = 7;
    const g = c.getContext('2d'); g.fillStyle = color;
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (rows[y][x] === '#') g.fillRect(x, y, 1, 1);
    cache[key] = c; return c;
  }

  PH.font = {
    W: 6, H: 8, // advance
    has: (ch) => !!F[ch],
    // Draw text. opts: {color, glitch, seed, shadow, wobble, scale}
    draw(ctx, text, x, y, opts) {
      opts = opts || {};
      const color = opts.color || '#e8e0d0';
      const scale = opts.scale || 1;
      let str = String(text);
      if (opts.glitch) str = PH.glitchText(str, opts.glitch, opts.seed || 0);
      let cx = Math.round(x), cy = Math.round(y);
      for (let i = 0; i < str.length; i++) {
        const ch = str[i];
        if (ch === '\n') { cx = Math.round(x); cy += this.H * scale; continue; }
        let ox = 0, oy = 0;
        if (opts.wobble) {
          oy = Math.round(Math.sin(PH.time * 7 + i * 1.3) * opts.wobble);
          ox = Math.round(Math.sin(PH.time * 5.1 + i * 0.7) * opts.wobble * 0.5);
        }
        if (opts.shadow) ctx.drawImage(glyphCanvas(ch, opts.shadow), cx + ox + 1, cy + oy + 1, 5 * scale, 7 * scale);
        ctx.drawImage(glyphCanvas(ch, color), cx + ox, cy + oy, 5 * scale, 7 * scale);
        cx += this.W * scale;
      }
      return cx;
    },
    width(text, scale) { return String(text).length * this.W * (scale || 1); },
    drawCentered(ctx, text, cx, y, opts) { this.draw(ctx, text, cx - this.width(text, opts && opts.scale) / 2, y, opts); },
    drawRight(ctx, text, rx, y, opts) { this.draw(ctx, text, rx - this.width(text, opts && opts.scale), y, opts); },
  };
